            "your saved reports on your phone.\n\n" +
            "Your choice\n" +
            "You can show the AI privacy notice again from this Settings screen."

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val themeMode = AppSettings.themeMode
    var popup by remember { mutableStateOf<InfoPopup?>(null) }
    var noticeReset by remember { mutableStateOf(false) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Settings") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                }
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .verticalScroll(rememberScrollState())
        ) {
            SectionHeader("Appearance")
            ThemeOption("Follow system", themeMode == ThemeMode.System) {
                AppSettings.setThemeMode(context, ThemeMode.System)
            }
            ThemeOption("Light", themeMode == ThemeMode.Light) {
                AppSettings.setThemeMode(context, ThemeMode.Light)
            }
            ThemeOption("Dark", themeMode == ThemeMode.Dark) {
                AppSettings.setThemeMode(context, ThemeMode.Dark)
            }

            HorizontalDivider(modifier = Modifier.padding(vertical = 8.dp))

            SectionHeader("Notifications")
            ListItem(
                headlineContent = { Text("Notification settings") },
                supportingContent = {
                    Text("Open your phone's settings for this app. Medicine reminders will use these.")
                },
                leadingContent = { Icon(Icons.Default.Notifications, contentDescription = null) },
                modifier = Modifier.clickable {
                    val intent = Intent(Settings.ACTION_APP_NOTIFICATION_SETTINGS)
                        .putExtra(Settings.EXTRA_APP_PACKAGE, context.packageName)
                    context.startActivity(intent)
                }
            )

            HorizontalDivider(modifier = Modifier.padding(vertical = 8.dp))

            SectionHeader("Privacy and information")
            ListItem(
                headlineContent = { Text("Privacy information") },
                supportingContent = { Text("How your reports are stored and what is sent online") },
                leadingContent = { Icon(Icons.Default.Lock, contentDescription = null) },
                modifier = Modifier.clickable { popup = InfoPopup.Privacy }
            )
            ListItem(
                headlineContent = { Text("Show the AI privacy notice again") },
                supportingContent = {
                    Text(
                        if (noticeReset) {
                            "Done. The notice will appear before your next explanation."
                        } else {
                            "Shows the preview of what is sent before the next explanation"
                        }
                    )
                },
                leadingContent = { Icon(Icons.Default.Refresh, contentDescription = null) },
                modifier = Modifier.clickable {
                    PrivacyPrefs.clearAiNoticeAccepted(context)
                    noticeReset = true
                }
            )
            ListItem(
                headlineContent = { Text("Medical disclaimer") },
                supportingContent = { Text("What this app can and cannot do") },
                leadingContent = { Icon(Icons.Default.Warning, contentDescription = null) },
                modifier = Modifier.clickable { popup = InfoPopup.Disclaimer }
            )
            ListItem(
                headlineContent = { Text("About MediScanner AI") },
                supportingContent = { Text("Version ${BuildConfig.VERSION_NAME}") },
                leadingContent = { Icon(Icons.Default.Info, contentDescription = null) },
                modifier = Modifier.clickable { popup = InfoPopup.About }
            )
        }
    }

    when (popup) {
        InfoPopup.Disclaimer -> InfoDialog("Medical disclaimer", DISCLAIMER_TEXT) { popup = null }
        InfoPopup.Privacy -> InfoDialog("Privacy information", PRIVACY_TEXT) { popup = null }
        InfoPopup.About -> InfoDialog(
            "About MediScanner AI",
            "MediScanner AI helps you read your lab reports in plain language.\n\n" +
                    "Version ${BuildConfig.VERSION_NAME}\n\n" +
                    "Text is read from your report on your device with Google ML Kit. " +
                    "Explanations and doctor questions are generated by an AI service. " +
                    "Built with Kotlin and Jetpack Compose.\n\n" +
                    "This app is educational only and is not a substitute for professional " +
                    "medical advice."
        ) { popup = null }
        null -> {}
    }
}

@Composable
private fun SectionHeader(title: String) {
    Text(
        title,
        style = MaterialTheme.typography.titleSmall,
        color = MaterialTheme.colorScheme.primary,
        modifier = Modifier.padding(start = 16.dp, top = 16.dp, end = 16.dp, bottom = 4.dp)
    )
}

@Composable
private fun ThemeOption(label: String, selected: Boolean, onSelect: () -> Unit) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .selectable(selected = selected, onClick = onSelect, role = Role.RadioButton)
            .padding(horizontal = 16.dp, vertical = 12.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        RadioButton(selected = selected, onClick = null)
        Spacer(modifier = Modifier.width(16.dp))
        Text(label, style = MaterialTheme.typography.bodyLarge)
    }
}

@Composable
private fun InfoDialog(title: String, text: String, onDismiss: () -> Unit) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(title) },
        text = {
            Column(modifier = Modifier.verticalScroll(rememberScrollState())) {
                Text(text, style = MaterialTheme.typography.bodyMedium)
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("Close") }
        }
    )
}