            "It does NOT diagnose any condition, recommend or change any treatment or " +
            "medicine, replace your doctor, or give definite medical conclusions.\n\n" +
            "Text is read from your report automatically and explanations are generated by " +
            "an AI service. Both can contain mistakes, so always check against your original " +
            "report.\n\n" +
            "Always discuss your results, and any medicine you take, with a qualified " +
            "healthcare professional. In an emergency, contact your local emergency number."

private const val PRIVACY_TEXT =
    "Your reports\n" +
            "Saved reports (the text, explanation and questions) are stored only in this " +
            "app's private storage on your phone. Cloud backup of the app is turned off. " +
            "There is no sign-in. Deleting a report in History removes it from your phone.\n\n" +
            "What is sent over the internet\n" +
            "To explain a report or generate doctor questions, the report's text is sent to " +
